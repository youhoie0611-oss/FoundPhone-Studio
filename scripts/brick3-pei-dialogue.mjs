export function injectBrick3PeiDialogue(story) {
  if (story.id !== "between-the-lines-b-demo") return story;
  const chat = story.chats.find(c => c.app === "kakao" && c.title === "裴知聿");
  if (!chat) throw Error("Brick3 Pei chat not found");
  const found = new Set();
  for (const msg of chat.messages) {
    if (Object.prototype.hasOwnProperty.call(peiDialogue,msg.id)) {
      if (msg.senderId === "owner") throw Error("Cannot rewrite player choice " + msg.id);
      msg.body = peiDialogue[msg.id];
      found.add(msg.id);
    }
  }
  const missing = Object.keys(peiDialogue).filter(id => !found.has(id));
  if (missing.length) throw Error("Missing Pei dialogue IDs: " + missing.join(","));
  return story;
}
